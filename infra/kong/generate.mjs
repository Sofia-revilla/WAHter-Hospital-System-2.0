// Writes infra/kong/kong.template.yml from routes.mjs (npm run kong:generate).
// The template is committed; start.sh fills in the secrets when Kong starts.

import { writeFileSync } from "node:fs";
import { PUBLIC_PATHS, ROLES, ROUTES, SERVICES } from "./routes.mjs";

const consumerFor = (role) => `role-${role.toLowerCase()}`;
const list = (items) => `[${items.join(", ")}]`;

const out = [];
const line = (text = "") => out.push(text);

line("# GENERATED by infra/kong/generate.mjs from routes.mjs. Edit routes.mjs and run");
line("# `npm run kong:generate`, don't edit this file by hand.");
line("#");
line("# Kong in DB-less mode: this file is the whole gateway config. start.sh swaps");
line("# __JWT_SECRET__ and __GATEWAY_LOG_SECRET__ for the real values at start-up,");
line("# so the secrets live only in .env.");
line('_format_version: "3.0"');
line();
line("# One consumer per role. A token's `rk` claim names its consumer, and the");
line("# consumer's ACL group is what the per-route allow lists check.");
line("consumers:");
for (const role of ROLES) {
  line(`  - username: ${consumerFor(role)}`);
  line("    jwt_secrets:");
  line(`      - key: ${consumerFor(role)}`);
  line("        secret: __JWT_SECRET__");
  line("        algorithm: HS256");
  line("    acls:");
  line(`      - group: ${role}`);
}
line();
line("plugins:");
line("  # nginx serves the app from the same origin, but two callers come from");
line("  # elsewhere: `npm run dev:web` on :3000/:3001, and the Vercel site when it's");
line("  # pointed at this stack through the demo tunnel (see README)");
line("  - name: cors");
line("    config:");
line("      origins:");
line('        - "http://localhost:3000"');
line('        - "http://localhost:3001"');
line('        - "http://localhost:8080"');
line("        - 'https://wahter-hospital-system(-[a-z0-9-]+)?\\.vercel\\.app'");
line("      methods: [GET, POST, PATCH, OPTIONS]");
line("      headers: [Authorization, Content-Type]");
line("      exposed_headers: [Content-Disposition, X-Row-Limit-Hit]");
line("      max_age: 3600");
line("  - name: rate-limiting");
line("    config:");
line("      minute: 600");
line("      policy: local");
line("  - name: correlation-id");
line("    config:");
line("      header_name: X-Request-ID");
line("      generator: uuid");
line("      echo_downstream: true");
line("  # US-41: Kong's 401s and 403s never reach a service, so Kong reports every");
line("  # request to the Audit Log, which keeps only the denied ones");
line("  - name: http-log");
line("    config:");
line("      http_endpoint: http://audit-log:3000/api/audit-log/internal/gateway-log");
line("      method: POST");
line("      headers:");
line("        X-Gateway-Secret: __GATEWAY_LOG_SECRET__");
line("      queue:");
line("        max_batch_size: 20");
line("        max_coalescing_delay: 2");
line();
line("# Short timeouts on purpose: Kong's defaults (60s, 5 retries) left the app");
line("# waiting a full minute on a stopped container before reporting it down.");
line("services:");

const jwt = [
  "          - name: jwt",
  "            config:",
  "              key_claim_name: rk",
  "              claims_to_verify: [exp]",
  "              run_on_preflight: false",
];

for (const service of SERVICES) {
  line(`  - name: ${service}`);
  line(`    url: http://${service}:3000`);
  line("    connect_timeout: 2000");
  line("    read_timeout: 15000");
  line("    write_timeout: 15000");
  line("    retries: 1");
  line("    routes:");
  const open = [...(PUBLIC_PATHS[service] ?? []), `/api/${service}/health`, `/api/${service}/docs`];
  line(`      - name: ${service}-public`);
  line(`        paths: ${list(open)}`);
  line("        strip_path: false");
  for (const route of ROUTES.filter((candidate) => candidate.service === service)) {
    line(`      - name: ${service}-${route.name}`);
    // OPTIONS too, so the CORS plugin can answer a browser's preflight
    line(`        methods: ${list([...route.methods, "OPTIONS"])}`);
    line(`        paths: ['${route.path}']`);
    line("        strip_path: false");
    if (route.path.startsWith("~")) line("        regex_priority: 10");
    line("        plugins:");
    if (route.internalOnly) {
      line("          - name: request-termination");
      line("            config:");
      line("              status_code: 404");
      line('              message: "Not found"');
      continue;
    }
    out.push(...jwt);
    line("          - name: acl");
    line("            config:");
    line(`              allow: ${list(route.roles)}`);
    line("              hide_groups_header: true");
  }
}

const target = new URL("./kong.template.yml", import.meta.url);
writeFileSync(target, `${out.join("\n")}\n`);
console.log(`kong.template.yml: ${ROLES.length} role consumers, ${ROUTES.length} routes across ${SERVICES.length} services`);
